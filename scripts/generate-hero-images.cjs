/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require('node:fs/promises');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');

async function main() {
  const root = path.resolve(__dirname, '..');
  const output = path.join(root, 'public', 'hero-preview');
  await fs.mkdir(output, { recursive: true });
  const images = {};
  let originalBytes = 0;
  let previewBytes = 0;
  async function visit(directory) {
    for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
      const file = path.join(directory, entry.name);
      if (entry.isDirectory()) { await visit(file); continue; }
      if (!/\.(jpe?g|png|webp|avif)$/i.test(entry.name)) continue;
      const input = await fs.readFile(file);
      const hash = crypto.createHash('sha256').update(input).update('640x1280-q50-v1').digest('hex').slice(0, 20);
      const name = `${hash}.webp`;
      const preview = await sharp(input).rotate().resize({ width: 640, height: 1280, fit: 'inside', withoutEnlargement: true }).webp({ quality: 50 }).toBuffer();
      await fs.writeFile(path.join(output, name), preview);
      images['/' + path.relative(path.join(root, 'public'), file).split(path.sep).join('/')] = `/hero-preview/${name}`;
      originalBytes += input.length;
      previewBytes += preview.length;
    }
  }
  await visit(path.join(root, 'public', 'demo'));
  await fs.writeFile(path.join(root, 'lib', 'hero-preview-images.ts'),
    '// Generated by npm run images:hero. Originals remain unchanged.\n' +
    `export const heroPreviewImages: Record<string, string> = ${JSON.stringify(images, null, 2)};\n`);
  console.log(JSON.stringify({ images: Object.keys(images).length, originalBytes, previewBytes, reduction: `${(100 * (1 - previewBytes / originalBytes)).toFixed(1)}%` }));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
