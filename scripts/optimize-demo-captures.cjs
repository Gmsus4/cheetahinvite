/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require('node:fs/promises');
const path = require('node:path');
const sharp = require('sharp');

async function main() {
  const root = path.resolve(__dirname, '..');
  const source = path.resolve(process.argv[2] || path.join(root, '.next', 'demo-captures'));
  const captures = JSON.parse(await fs.readFile(path.join(source, 'manifest.json'), 'utf8'));
  const output = path.join(root, 'public', 'demo-preview');
  await fs.mkdir(output, { recursive: true });
  const images = {};
  let bytes = 0;
  for (const { key } of captures) {
    if (!/^[a-f0-9]{24}$/.test(key)) throw new Error('Invalid capture key');
    const input = path.join(source, `${key}.jpg`);
    const metadata = await sharp(input).metadata();
    if (metadata.width !== 390 || metadata.height !== 830) throw new Error('Capture must be 390 by 830 pixels');
    const image = await sharp(input).webp({ quality: 80 }).toBuffer();
    await fs.writeFile(path.join(output, `${key}.webp`), image);
    images[key] = `/demo-preview/${key}.webp`;
    bytes += image.length;
  }
  await fs.writeFile(path.join(root, 'lib', 'demo-preview-images.ts'),
    '// Generated by npm run images:demo from browser captures. Keys identify published content.\n' +
    `export const demoPreviewImages: Record<string, string> = ${JSON.stringify(images, null, 2)};\n`);
  console.log(JSON.stringify({ captures: captures.length, bytes }));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
