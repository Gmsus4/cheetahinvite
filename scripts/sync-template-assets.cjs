/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS helper runs directly in Node before dev/build. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const events = { wedding: 'boda', birthday: 'cumpleanos', graduation: 'graduacion', baby_shower: 'baby-shower', anniversary: 'aniversario' };
const slots = { topLeft: 'Superior_izquierdo', topRight: 'Superior_derecho', bottomLeft: 'Inferior_izquierdo', bottomRight: 'Inferior_derecho', separator: 'separador', flower: 'flor', decoration: 'decorate' };
const normalizeName = (name) => name.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[\s_-]+/g, '');
const templates = [];
for (const [eventType, folder] of Object.entries(events)) {
  for (let number = 1; number <= 3; number++) {
    const id = `plantilla${number}`;
    const source = path.join(root, 'recursos-plantillas', folder, id);
    fs.mkdirSync(source, { recursive: true });
    const files = fs.readdirSync(source);
    const configPath = path.join(source, 'plantilla.json');
    const config = fs.existsSync(configPath) ? JSON.parse(fs.readFileSync(configPath, 'utf8')) : {};
    if (config.primaryColor !== undefined && !/^#[0-9a-f]{6}$/i.test(config.primaryColor)) throw new Error(`Color principal inválido en ${folder}/${id}/plantilla.json`);
    const assets = {};
    for (const [slot, stem] of Object.entries(slots)) {
      const matches = files.filter((name) => normalizeName(path.parse(name).name) === normalizeName(stem) && ['.png', '.webp', '.svg', '.avif', '.jpg', '.jpeg'].includes(path.extname(name).toLowerCase()));
      if (matches.length > 1) throw new Error(`Hay varios archivos para ${stem} en ${folder}/${id}. Conserva uno solo.`);
      const file = matches[0];
      if (!file) continue;
      const target = path.join(root, 'public', 'plantillas', folder, id);
      fs.mkdirSync(target, { recursive: true });
      const filename = `${slot}${path.extname(file).toLowerCase()}`;
      fs.copyFileSync(path.join(source, file), path.join(target, filename));
      assets[slot] = `/plantillas/${folder}/${id}/${filename}`;
    }
    templates.push({ id, eventType, label: `Plantilla ${number}`, available: Object.keys(assets).length > 0, accent: config.primaryColor ?? null, assets });
  }
}
fs.writeFileSync(path.join(root, 'lib', 'generated-invitation-templates.ts'), `// Generated by npm run templates:sync. Originals stay in recursos-plantillas.\nexport const templateManifest = ${JSON.stringify(templates, null, 2)};\n`);
console.log(`Plantillas sincronizadas: ${templates.filter((template) => template.available).length} disponibles de ${templates.length}.`);
